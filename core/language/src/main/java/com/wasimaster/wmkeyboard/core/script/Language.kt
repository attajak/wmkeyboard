/**
 * A language the keyboard offers, and everything language-level that used to hang
 * off the `InputMode`/`KeyboardLanguage` enums: the dictionary folder, the
 * dictation/hint locale, which layouts belong to it, and which script it writes.
 *
 * [id] is a stable BCP-47-ish key ("en", "bn", "fr", "sr-Cyrl" …). It doubles as
 * the on-disk name for the language's imported-dictionary folder, so it must not
 * change once shipped. [layoutIds] are the built-in (or asset) layouts grouped
 * under this language on the Languages screen.
 *
 * [bundledDictionary] is true only where the APK actually ships a word list
 * (English, Bengali). Whether a language can be *glided* is deliberately not a
 * flag here: it depends on which layout is showing and whether its keys spell
 * the language, neither of which a language-level constant can know. The IME
 * measures it — see `KeyboardUiState.glideReady`.
 */
data class LanguageDef(
    val id: String,
    val displayName: String,
    val englishName: String,
    val script: ScriptId,
    val localeTag: String,
    val layoutIds: List<String>,
    val bundledDictionary: Boolean = false,
    /**
     * The digit glyphs this language draws and types when the numeral-system
     * setting is left on Auto. Defaults to Latin `0-9`; scripts with their own
     * numerals (Arabic, Persian/Urdu, Bengali/Assamese, the Devanagari
     * languages) set their own. A manual override in settings ignores this.
     */
    val numeralSystem: NumeralSystem = NumeralSystem.LATIN,
    /**
     * The punctuation marks this language keeps a no-break space in *front* of,
     * against the keyboard's general rule that a mark hugs the word before it.
     * Empty for every language that does not do this, which is nearly all of
     * them — see [SpacedPunctuation] for what the exceptions want and why.
     */
    val spacedPunctuation: String = "",
    /**
     * The marks this language keeps a no-break space *after* — the other half
     * of [spacedPunctuation], and empty for the same near-totality of
     * languages. Today only the opening guillemet, in the languages written to
     * the French standard.
     */
    val spacedOpeners: String = "",
) {
    /** English-language convenience, preserving the old `InputMode.isEnglish` reads. */
    val isEnglish: Boolean get() = id == "en"
}

